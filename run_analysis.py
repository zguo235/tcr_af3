#!/usr/bin/env python3
"""Run the manuscript analysis scripts with external inputs and separate outputs."""

import argparse
import csv
import hashlib
import os
from pathlib import Path
import shlex
import subprocess
import sys

PACKAGE_ROOT = Path(__file__).resolve().parent
STEPS = ("structural", "heavy_atoms", "accuracy", "per_template",
         "prioritization", "features", "overlap", "plots")


def check_inputs(data_root, supplementary_dir, steps, verify_hashes=False):
    """Check manifested inputs for selected steps; return missing/mismatched files.

    Roots are Paths. steps is an iterable of workflow step names. Hash checks
    are optional because structural confidence files can be large. Files
    generated by selected upstream steps do not need supplied table copies.
    """
    selected = set(steps)
    generated = set()
    if "features" in selected:
        generated.update(["S15.csv", "S16.csv", "S17.csv"])
    if "prioritization" in selected:
        generated.add("S18.csv")
    problems = []
    checked = 0
    with (PACKAGE_ROOT / "INPUT_MANIFEST.tsv").open(newline="") as handle:
        for row in csv.DictReader(handle, delimiter="\t"):
            relevant = selected.intersection(row["steps"].split(","))
            if not relevant:
                continue
            if relevant == {"plots"} and row["root"] == "supplementary" and row["path"] in generated:
                continue
            root = data_root if row["root"] == "data" else supplementary_dir
            path = root / row["path"]
            checked += 1
            if not path.is_file():
                problems.append(f"Missing: {path}")
            elif verify_hashes:
                with path.open("rb") as source:
                    digest = hashlib.file_digest(source, "sha256").hexdigest()
                if digest != row["sha256"]:
                    problems.append(f"Checksum differs from manuscript input: {path}")
    print(f"Checked {checked} inputs; {len(problems)} issue(s).", flush=True)
    return problems


def build_commands(data_root, supplementary_dir, output_root, steps):
    """Return ordered (step, argv, stdout_path) commands for existing scripts.

    stdout_path is None for normal console output; otherwise capture a printed
    summary or generated LaTeX fragment there. No commands are executed here.
    """
    commands = []
    selected = set(steps)
    tables = output_root / "supplementary_tables"
    figures = output_root / "figures"
    structures = output_root / "structural"

    def add(step, script, *arguments, stdout_path=None):
        """Append one selected script call with paths converted to strings."""
        if step in selected:
            commands.append((step, [sys.executable, str(PACKAGE_ROOT / "scripts" / script),
                                   *map(str, arguments)], stdout_path))

    pairs = data_root / "tcr3d/unbound-bound.csv"
    prepared = data_root / "tcr3d/prepared"
    af_server = data_root / "tcr3d/AF_predictions"
    references = data_root / "tcr3d/alphafold_input"
    bound_csv = structures / "bound_unbound_comparison.csv"
    af_csv = structures / "af_prediction_comparison.csv"
    add("structural", "compare_bound_unbound.py", "--csv", pairs,
        "--prepared-dir", prepared, "--output", bound_csv)
    add("structural", "compare_af_predictions.py", "--csv", pairs,
        "--af-dir", af_server, "--ref-dir", references, "--bu-csv", bound_csv,
        "--model", 0, "--output", af_csv)
    add("structural", "print_table1_cdr_rmsd.py", "--csv", bound_csv,
        stdout_path=tables / "S2_summary.txt")
    add("structural", "print_table2_af_rmsd.py", "--af-csv", af_csv,
        "--bu-csv", bound_csv, "--model", 0, "--per-complex-output", tables / "S3.csv",
        stdout_path=structures / "Table1_ca_summary.txt")
    add("structural", "plot_cdr_rmsd_histograms.py", "--input", bound_csv,
        "--output-pdf", figures / "figure1_rmsd_histograms.pdf")
    add("heavy_atoms", "analyze_tcr_heavy_atom_rmsd.py", "--metadata", pairs,
        "--bound-dir", prepared / "bound", "--unbound-dir", prepared / "unbound",
        "--af-dir", af_server, "--reference-dir", references,
        "--output-complex", tables / "S4.csv", "--output-residue", tables / "S5.csv",
        "--output-summary", structures / "heavy_atom_summary.csv",
        "--output-figure-pdf", figures / "tcr_residue_wise_rmsd.pdf",
        "--output-figure-png", figures / "tcr_residue_wise_rmsd.png")
    add("accuracy", "ddg_accuracy_uncertainty.py",
        "--intervals-out", tables / "S10.csv", "--comparisons-out", tables / "S11.csv")
    add("per_template", "supp_per_template_metrics.py",
        "--out-dir", tables, "--ci-out", tables / "S12.csv")
    add("prioritization", "cdr_prioritization_per_template.py",
        "--min-cdr-mutants", 20, "--templates", "1AO7", "1MI5", "2BNR", "3QDJ",
        "--out-table", tables / "S18.csv", "--out-summary", tables / "Table3_summary.csv")
    add("prioritization", "cdr_prioritization_1ao7.py", "--out", tables / "S19.csv",
        "--top10-out", tables / "S20.csv")
    add("features", "analyze_af3_wt_error_features.py",
        "--template-output", tables / "S15.csv", "--mutation-output", tables / "S16.csv",
        "--associations-output", tables / "S17.csv")
    add("overlap", "analyze_template_overlap_performance.py",
        "--repository", data_root, "--workspace", data_root / "frontiersin_revision_v3",
        "--output-dir", output_root / "template_overlap")
    add("overlap", "format_template_overlap_tables.py",
        "--source-dir", output_root / "template_overlap", stdout_path=tables / "S21_S22.tex")
    feature_tables = tables if "features" in selected else supplementary_dir
    candidate_tables = tables if "prioritization" in selected else supplementary_dir
    add("plots", "plot_af3_wt_error_features.py", "--template-table", feature_tables / "S15.csv",
        "--mutation-table", feature_tables / "S16.csv", "--associations-table", feature_tables / "S17.csv",
        "--output-pdf", figures / "af3_wt_error_features.pdf",
        "--output-png", figures / "af3_wt_error_features.png")
    add("plots", "plot_cdr_prioritization_boxplot.py", "--input", candidate_tables / "S18.csv",
        "--output-pdf", figures / "cdr_prioritization_boxplot.pdf",
        "--output-png", figures / "cdr_prioritization_boxplot.png")
    add("plots", "plot_af3_mutant_ensemble_saturation.py", "--input", supplementary_dir / "S13.csv",
        "--output-pdf", figures / "af3_mutant_ensemble_saturation.pdf",
        "--output-png", figures / "af3_mutant_ensemble_saturation.png")
    return commands


def main():
    """Validate inputs, then run only the requested CPU analysis steps."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", type=Path, default=PACKAGE_ROOT / "data")
    parser.add_argument("--supplementary-dir", type=Path)
    parser.add_argument("--output-dir", type=Path, default=PACKAGE_ROOT / "results")
    parser.add_argument("--steps", nargs="+", choices=STEPS, default=list(STEPS))
    parser.add_argument("--check-inputs", action="store_true", help="Check inputs and exit without running analyses.")
    parser.add_argument("--verify-hashes", action="store_true", help="Also compare inputs with the manuscript input checksums.")
    parser.add_argument("--dry-run", action="store_true", help="Print exact commands without executing them.")
    args = parser.parse_args()
    data_root = args.data_root.expanduser().resolve()
    supplementary_dir = (args.supplementary_dir or data_root / "frontiersin_revision_v3/supplementary_tables").expanduser().resolve()
    output_root = args.output_dir.expanduser().resolve()
    commands = build_commands(data_root, supplementary_dir, output_root, args.steps)
    if args.dry_run:
        for step, command, capture in commands:
            print(f"[{step}] {shlex.join(command)}" + (f" > {shlex.quote(str(capture))}" if capture else ""))
        return
    problems = check_inputs(data_root, supplementary_dir, args.steps, args.verify_hashes)
    if problems:
        parser.exit(1, "\n".join(problems) + "\nSee INPUTS.md for the external data layout.\n")
    if args.check_inputs:
        return
    env = os.environ.copy()
    env.update(FRONTIERS_DATA_ROOT=str(data_root), FRONTIERS_OUTPUT_ROOT=str(output_root),
               FRONTIERS_SUPPLEMENTARY_DIR=str(supplementary_dir), MPLBACKEND="Agg")
    env.setdefault("MPLCONFIGDIR", str(output_root / ".matplotlib"))
    for directory in [output_root / "supplementary_tables", output_root / "figures", output_root / "structural"]:
        directory.mkdir(parents=True, exist_ok=True)
    for step, command, capture in commands:
        print(f"[{step}] {Path(command[1]).name}", flush=True)
        if capture:
            with capture.open("w") as handle:
                subprocess.run(command, env=env, cwd=PACKAGE_ROOT, check=True, stdout=handle)
        else:
            subprocess.run(command, env=env, cwd=PACKAGE_ROOT, check=True)


if __name__ == "__main__":
    main()
